import numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import brentq

G_N = 1.0
C_MATTER = 1.0
A3_INIT = 6.0 * np.pi - 1.0
PHIDOT_INIT = np.sqrt(2.0) / A3_INIT


def bg_quantities(a, pb, pd, gh, lam):
    rho_A = C_MATTER / a**3
    rho_phys = rho_A * (1.0 - gh * pb)
    V = lam * pb**4 / 4.0
    H = np.sqrt(max((8.0 * np.pi * G_N / 3.0) * (rho_phys + pd**2 / 2.0 + V), 0.0))
    return {
        "rho_A": rho_A,
        "rho_phys": rho_phys,
        "Vp": lam * pb**3,
        "Vpp": 3.0 * lam * pb**2,
        "H": H,
        "Hdot": -4.0 * np.pi * G_N * (rho_phys + pd**2),
    }


def make_system(gh, lam, kk):
    """FINDING_P73/P74 system, reused verbatim. The Euler line carries the
    fifth force this file exists to measure."""

    def rhs(_t, y):
        a_, pb, pd, psi, psid, dph, dphd, drA, qm = y
        b = bg_quantities(a_, pb, pd, gh, lam)
        H, rho_A, rho_phys, Vp, Vpp = (b["H"], b["rho_A"], b["rho_phys"], b["Vp"], b["Vpp"])
        pdd = gh * rho_A - 3.0 * H * pd - Vp
        dp_phi = pd * dphd - psi * pd**2 - Vp * dph
        psidd = 4 * np.pi * G_N * dp_phi - 4 * H * psid - (2 * b["Hdot"] + 3 * H**2) * psi
        dphdd = (
            gh * drA
            + 2 * psi * (gh * rho_A - Vp)
            + 4 * psid * pd
            - 3 * H * dphd
            - (kk**2 / a_**2 + Vpp) * dph
        )
        drAd = -3 * H * drA + 3 * psid * rho_A + (kk**2 / a_**2) * qm / (1 - gh * pb)
        qmd = -3 * H * qm - rho_phys * psi + gh * rho_A * dph
        return [a_ * H, pd, pdd, psid, psidd, dphd, dphdd, drAd, qmd]

    return rhs


def initial_data(gh, lam, kk, psi0=1e-5, phidot0=None, dph0=1e-6, dphd0=0.0, drA0=1e-5):
    a0 = A3_INIT ** (1.0 / 3.0)
    pb0 = 0.0
    pd0 = PHIDOT_INIT if phidot0 is None else phidot0
    b = bg_quantities(a0, pb0, pd0, gh, lam)
    H0 = b["H"]
    drho_phi0 = pd0 * dphd0 - psi0 * pd0**2 + b["Vp"] * dph0
    drho_m0 = drA0 * (1 - gh * pb0) - gh * b["rho_A"] * dph0
    psid0 = (-(kk**2 / a0**2) * psi0 - 4 * np.pi * G_N * (drho_phi0 + drho_m0)) / (
        3 * H0
    ) - H0 * psi0
    qm0 = -(psid0 + H0 * psi0) / (4 * np.pi * G_N) + pd0 * dph0
    return [a0, pb0, pd0, psi0, psid0, dph0, dphd0, drA0, qm0]


_CACHE = {}


def run(gh, lam, kk, t_end, rtol=1e-10, **ic):
    """Integrate once per distinct (parameters, initial data) and reuse.

    # WHY: the gates below re-ask for the SAME trajectory at many evaluation
    # points (Part D alone wants four end-times per k). Re-integrating to
    # t=1e8 each time turned a minutes-long file into an hours-long one.
    # dense_output already lets one solution answer every query, so the only
    # thing missing was not throwing it away.
    """
    key = (gh, lam, kk, t_end, rtol, tuple(sorted(ic.items())))
    if key not in _CACHE:
        s = solve_ivp(
            make_system(gh, lam, kk),
            (1.0, t_end),
            initial_data(gh, lam, kk, **ic),
            rtol=rtol,
            atol=1e-20,
            dense_output=True,
        )
        assert s.success, f"integration failed gh={gh} lam={lam} k={kk} t_end={t_end}"
        _CACHE[key] = s
    return _CACHE[key]


def contrast(sol, gh, lam, tv):
    """delta_m := Delta_m / rho_phys, with Delta = drho - 3H*dq (P74's derived form)."""
    a_, pb, pd, psi, _psid, dph, _dphd, drA, qm = sol.sol(tv)
    b = bg_quantities(a_, pb, pd, gh, lam)
    delta_m = drA * (1 - gh * pb) - gh * b["rho_A"] * dph - 3 * b["H"] * qm
    return delta_m / b["rho_phys"]


def t_of_a(sol, a_target, t_lo, t_hi):
    """Invert a(t). Needed because a(t) differs between runs, so matched-t is
    NOT matched-a and comparing at matched t imports a background artifact."""
    f = lambda tv: sol.sol(tv)[0] - a_target  # noqa: E731
    if f(t_lo) * f(t_hi) > 0:
        return None
    return brentq(f, t_lo, t_hi, xtol=1e-8, rtol=1e-12)


def growth_a_matched(gh, lam, kk, a1, a2, t_end, **ic):
    """Growth of the contrast between two SCALE FACTORS, not two times."""
    s = run(gh, lam, kk, t_end, **ic)
    t1, t2 = t_of_a(s, a1, 1.0, t_end), t_of_a(s, a2, 1.0, t_end)
    if t1 is None or t2 is None:
        return None
    return contrast(s, gh, lam, t2) / contrast(s, gh, lam, t1)


def G_growth(gh, lam, kk, a1, a2, t_end, **ic):
    """G_growth := growth(coupling on) / growth(coupling OFF AT THE SAME lambda).

    # WHY the reference is (g_hat=0, lambda) and NOT (0, 0): switching off both
    # the coupling and the potential changes TWO things at once, and they do
    # different work -- lambda makes phibar oscillate in its well (FINDING_P70),
    # g_hat is the matter coupling. A (0,0) reference would charge the
    # potential's effect to the coupling. One assumption at a time: this
    # project's own Minimal Relaxation Rule, applied to a control.
    """
    num = growth_a_matched(gh, lam, kk, a1, a2, t_end, **ic)
    den = growth_a_matched(0.0, lam, kk, a1, a2, t_end, **ic)
    assert num is not None and den is not None, (
        f"a-anchor [{a1:.4g}, {a2:.4g}] not reachable by both runs at "
        f"g_hat={gh}, lambda={lam}, k={kk} -- move the anchor inside"
    )
    return num / den


